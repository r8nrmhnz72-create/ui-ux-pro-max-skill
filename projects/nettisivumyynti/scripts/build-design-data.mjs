// Exports the UI UX Pro Max tables the demo generator needs into one compact
// TypeScript module (src/lib/design-data.ts), so the same design knowledge runs in
// the browser preview and in the Vercel function without Python.
//
// Run from this folder after the data in src/ui-ux-pro-max/data changes:
//   node scripts/build-design-data.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.resolve(here, "../../../src/ui-ux-pro-max/data");
const OUT = path.resolve(here, "../src/lib/design-data.ts");

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.some((v) => v !== "")) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h.replace(/^﻿/, ""), (r[i] ?? "").trim()])));
}

const read = (f) => parseCsv(fs.readFileSync(path.join(DATA, f), "utf8"));
const pick = (row, cols) => Object.fromEntries(cols.filter((c) => row[c]).map((c) => [c, row[c]]));

const reasoning = new Map(read("ui-reasoning.csv").map((r) => [r.UI_Category.toLowerCase(), r]));

const domains = {
  product: {
    description: "Product / business types with recommended style, landing pattern, palette focus and design rules.",
    search: ["Product Type", "Keywords", "Primary Style Recommendation", "Key Considerations"],
    rows: read("products.csv").map((r) => {
      const why = reasoning.get(r["Product Type"].toLowerCase()) ?? {};
      return {
        ...pick(r, ["Product Type", "Keywords", "Primary Style Recommendation", "Secondary Styles", "Landing Page Pattern", "Color Palette Focus", "Key Considerations"]),
        ...pick(why, ["Color_Mood", "Typography_Mood", "Key_Effects", "Decision_Rules", "Anti_Patterns"]),
      };
    }),
  },
  style: {
    description: "UI styles (minimalism, glassmorphism, brutalism...) with colors, effects, CSS keywords and an implementation checklist.",
    search: ["Style Category", "Aliases", "Keywords", "Best For", "Type", "AI Prompt Keywords"],
    rows: read("styles.csv")
      .filter((r) => r.Status !== "deprecated")
      .map((r) => pick(r, ["Style Category", "Aliases", "Keywords", "Primary Colors", "Secondary Colors", "Effects & Animation", "Best For", "Do Not Use For", "Accessibility", "CSS/Technical Keywords", "Implementation Checklist", "Design System Variables"])),
  },
  color: {
    description: "Color palettes per product type as semantic tokens (primary, background, foreground, muted, border...).",
    search: ["Product Type", "Notes"],
    rows: read("colors.csv").map((r) => pick(r, ["Product Type", "Primary", "On Primary", "Secondary", "On Secondary", "Accent", "On Accent", "Background", "Foreground", "Card", "Card Foreground", "Muted", "Muted Foreground", "Border", "Ring", "Notes"])),
  },
  typography: {
    description: "Google Fonts pairings (heading + body) with mood, best use and the exact Google Fonts URL.",
    search: ["Font Pairing Name", "Category", "Mood/Style Keywords", "Best For", "Heading Font", "Body Font"],
    rows: read("typography.csv").map((r) => pick(r, ["Font Pairing Name", "Category", "Heading Font", "Body Font", "Mood/Style Keywords", "Best For", "Google Fonts URL", "Notes"])),
  },
  landing: {
    description: "Landing page patterns: section order, CTA placement, color strategy and conversion tips.",
    search: ["Pattern Name", "Aliases", "Keywords", "Conversion Optimization", "Section Order"],
    rows: read("landing.csv").map((r) => pick(r, ["Pattern Name", "Keywords", "Section Order", "Primary CTA Placement", "Color Strategy", "Recommended Effects", "Conversion Optimization"])),
  },
  ux: {
    description: "Web UX and accessibility rules (do / don't, severity): contrast, focus, motion, forms, touch targets...",
    search: ["Category", "Issue", "Description", "Platform"],
    rows: read("ux-guidelines.csv")
      .filter((r) => r.Platform === "All" || r.Platform === "Web")
      .map((r) => pick(r, ["Category", "Issue", "Description", "Do", "Don't", "Code Example Good", "Severity"])),
  },
};

fs.writeFileSync(
  OUT,
  "// Generated by scripts/build-design-data.mjs from src/ui-ux-pro-max/data. Do not edit by hand.\n" +
    'import type { DesignData } from "./design-search";\n\n' +
    `const data: DesignData = ${JSON.stringify(domains)};\n\nexport default data;\n`,
);
const sizes = Object.entries(domains).map(([k, d]) => `${k}=${d.rows.length}`).join(" ");
console.log(`wrote ${path.relative(process.cwd(), OUT)} (${Math.round(fs.statSync(OUT).size / 1024)} KB): ${sizes}`);
